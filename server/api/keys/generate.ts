import { defineEventHandler, readBody } from 'h3';
import { verifyToken, readDb, mutateDb, addTx, nextId, licenseKey, keyBatchCost } from '../../../src/lib/gh-store.server';
import type { DbKey } from '../../../src/lib/types';

export default defineEventHandler(async (event) => {
  const body = await readBody(event);
  const { token, game, hours, devices, qty = 1, customKey } = body as {
    token: string; game: string; hours: number | null; devices: number; qty?: number; customKey?: string;
  };
  if (!token || !game || !devices) return { ok: false, error: 'Missing fields' };
  const v = await verifyToken(token);
  if (!v) return { ok: false, error: 'Session expired' };
  const { db } = await readDb();
  const me = db.users.find((x) => x.id === v.uid);
  if (!me || me.status !== 'active') return { ok: false, error: 'Session expired' };

  const price = hours === null ? 0 : (db.settings.prices.find((p) => p.hours === hours)?.price ?? -1);
  if (price < 0) return { ok: false, error: 'Unknown duration plan' };
  if (hours === null && me.role !== 'owner') return { ok: false, error: 'Lifetime keys are Owner-only' };

  const cost = keyBatchCost(me.role, price, qty);
  if (me.role !== 'owner' && cost > me.balance)
    return { ok: false, error: `Insufficient balance — need ₹${cost}, have ₹${me.balance}` };

  const now = new Date().toISOString();
  const expires_at = hours ? new Date(Date.now() + hours * 3_600_000).toISOString() : null;
  const made: string[] = [];

  // Pre-generate license keys before the synchronous mutation
  const preMade: string[] = [];
  if (customKey) {
    preMade.push(customKey.trim().toUpperCase());
  } else {
    for (let i = 0; i < qty; i++) {
      preMade.push(await licenseKey());
    }
  }

  const result = await mutateDb((d2) => {
    const u = d2.users.find((x) => x.id === me.id);
    if (!u || u.status !== 'active') return;
    if (me.role !== 'owner' && cost > u.balance) return;

    if (customKey) {
      const ck = customKey.trim().toUpperCase();
      if (d2.keys.some((x) => x.license_key === ck)) { throw new Error('custom_taken'); }
      d2.keys.push({
        id: nextId(d2, 'key'), license_key: ck, game, duration_hours: hours, max_devices: devices, devices: [],
        created_by: u.id, created_by_name: u.username, created_at: now, expires_at,
      });
      made.push(ck);
    } else {
      for (const license of preMade) {
        d2.keys.push({
          id: nextId(d2, 'key'), license_key: license, game, duration_hours: hours, max_devices: devices, devices: [],
          created_by: u.id, created_by_name: u.username, created_at: now, expires_at,
        });
        made.push(license);
      }
    }
    if (me.role !== 'owner') u.balance -= cost;
    const label = hours ? `${hours}h` : 'lifetime';
    addTx(d2, u, 'key_generate', `Generated ${qty} key(s) · ${game} · ${label} · ${devices} device(s)`, me.role === 'owner' ? 0 : -cost, me.role === 'owner' ? null : u.balance);
  }, `keys generated by ${me.username}`);

  if (made.length === 0) return { ok: false, error: 'Custom key name already taken' };
  return { ok: true, keys: made, charged: cost, balance: result.users.find((x) => x.id === me.id)!.balance };
});
